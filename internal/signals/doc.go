// Package signals — закрытый каталог именованных сигналов метрик и интерфейс Provider (ADR-0032 §2, §4, §5).
//
// Правила диагностики знают только имена сигналов и типизированные результаты (Value, Gap), но не PromQL, не метки
// и не имена метрик: источник заменяем, а правила тестируются фикстурами без Prometheus. Метрики — необязательный
// источник доказательств: отсутствие стека, отказ RBAC, таймаут или пустой ответ выражаются причиной (Reason) у
// сигнала, а не ошибкой расследования и не значением 0.
//
// Пакет не обращается к кластеру сам: запрос выполняет Querier, которого слой связки строит поверх
// opsplatform.MetricsReader. Поэтому пакет не импортирует ни internal/k8s, ни opsplatform, ни diagnose
// (проверяет статический тест платформы, internal/k8s/opsplatform_static_test.go).
//
// Имя internal/metrics занято метриками самого Kubron (ADR-0022), поэтому пакет назван signals.
package signals
